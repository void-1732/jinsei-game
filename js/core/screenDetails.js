export const screenDetails = Object.freeze(Object.fromEntries(allScreens.map(screen => {
  const spec = specs[screen.id];
  if (!spec) throw new Error(`詳細仕様未登録: ${screen.id}`);
  const [fields, ...links] = spec;
  const related = links.map(([label, target]) => {
    if (!findScreen(target)) throw new Error(`リンク先未登録: ${screen.id} -> ${target}`);
    return Object.freeze({ label, target });
  });
  return [screen.id, Object.freeze({ fields: Object.freeze(fields), related: Object.freeze(related),
    dataStatus: '未接続', plannedActions: Object.freeze(actionLabels(screen.id)) })];
})));
function actionLabels(id) {
  if (id.startsWith('SETTING')) return ['設定・保存操作（今後の段階）'];
  if (id.startsWith('HISTORY') || id.endsWith('08') || id.endsWith('07')) return ['履歴を絞り込む（データ導入後）'];
  if (id.startsWith('EVENT')) return ['人生イベントを操作（第6段階以降）'];
  if (id.startsWith('PERSON')) return ['人物を選択・編集（第4段階以降）'];
  if (id.startsWith('EDU')) return ['学業・進路を操作（第4段階以降）'];
  return ['ゲーム情報を操作（今後の段階）'];
}
export function assertDetails() {
  if (Object.keys(screenDetails).length !== 61) throw new Error('詳細画面数が61ではありません');
  for (const s of allScreens) {
    const d = screenDetails[s.id];
    if (!d || d.fields.length < 4 || d.related.some(link => !findScreen(link.target))) throw new Error(`画面詳細不備: ${s.id}`);
  }
  return true;
}
assertDetails();
