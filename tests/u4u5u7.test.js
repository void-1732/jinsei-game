test('U7：20代に選んだ資産方針が35歳・50歳で分岐として再登場する',()=>{
 const progress=createStoryProgress();
 const first=createBranchingEvent(progress,{year:2025,month:2},200,25);
 assert.equal(first.branch.thread,'financialFuture');
 assert.equal(first.options.length,3);
 const selected=first.options.find(o=>o.path==='challenge');
 assert.ok(selected);
 recordBranchChoice(progress,first,selected,25);
 assert.equal(progress.scheduled.find(x=>x.thread==='financialFuture').dueAge,35);
 const sequel=createBranchingEvent(progress,{year:2035,month:2},350,35);
 assert.equal(sequel.branch.stage,2);
 assert.match(sequel.description,/技能|20代/);
 assert.ok(sequel.options.some(o=>o.path==='challenge'));
 recordBranchChoice(progress,sequel,sequel.options.find(o=>o.path==='challenge'),35);
 const final=createBranchingEvent(progress,{year:2050,month:2},500,50);
 assert.equal(final.branch.stage,3);
 assert.equal(final.branch.thread,'financialFuture');
 assert.equal(validateStoryProgress(progress),true);
});
