test('60歳総合クリアは5分野の評価を用い、寿命・死亡とは独立した記録',()=>{
 const g=adult(),s=structuredClone(g.getState());
 s.timeline={year:2060,month:5,ageYears:60,turnsElapsed:500,monthsElapsed:724};
 s.turnActions={turn:500,used:0,lastAction:null,categories:[]};
 s.finances.cash=12000000;
 s.finances.career.job='事務職';s.finances.career.experience=144;
 s.health.physical=85;s.health.mental=80;
 for(const p of s.people)if(p.role!=='本人')p.relationship=85;
 assert.equal(validateGameState(s),true);
 const report=seniorClearAssessment(s);
 assert.equal(report.eligible,true);assert.equal(report.breakdown.length,5);
 assert.equal(report.breakdown.reduce((a,b)=>a+b.score,0),report.score);
 assert.equal(report.canClear,true);
 const first=recordSeniorClear(s);assert.ok(first);assert.equal(first.age,60);
 assert.equal(recordSeniorClear(s),null);
 assert.equal(s.ending.dead,false);
 assert.equal(validateSeniorClear(s.seniorClear),true);
 assert.equal(validateGameState(s),true);
 const restored=createGameStore({interactiveChoices:true});
 assert.equal(restored.loadState(s).ok,true);
 assert.equal(restored.getState().seniorClear.score,first.score);
});
